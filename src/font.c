const char *const *font_glyph(char ch) {
    ch = (char)toupper((unsigned char)ch);
    for (size_t i = 0; i < sizeof GLYPHS / sizeof GLYPHS[0]; i++)
        if (GLYPHS[i].ch == ch) return GLYPHS[i].rows;
    return NULL;
}

/* Each glyph is 5 dots wide plus 1 dot of spacing. */
int text_width(const char *s, int scale) {
    int n = (int)strlen(s);
    return n ? (n * (FONT_W + 1) - 1) * scale : 0;
}

void draw_text(SDL_Renderer *r, const char *s, int x, int y, int scale, SDL_Color c) {
    set_color(r, c);
    for (; *s; s++, x += (FONT_W + 1) * scale) {
        const char *const *g = font_glyph(*s);
        if (!g) continue;
        for (int row = 0; row < FONT_H; row++)
            for (int col = 0; col < FONT_W; col++)
                if (g[row][col] == '#') {
                    SDL_Rect d = { x + col * scale, y + row * scale, scale, scale };
                    SDL_RenderFillRect(r, &d);
                }
    }
}

void draw_text_shadow(SDL_Renderer *r, const char *s, int x, int y, int scale, SDL_Color c) {
    int off = scale / 3 > 1 ? scale / 3 : 1;
    SDL_Color shadow = { 0, 0, 0, 160 };
    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
    draw_text(r, s, x + off, y + off, scale, shadow);
    draw_text(r, s, x, y, scale, c);
}

Canvas text_canvas(const char *s, uint32_t col) {
    int w = text_width(s, 1);
    Canvas c = canvas_new(w > 0 ? w : 1, FONT_H);
    for (int x = 0; *s; s++, x += FONT_W + 1) {
        const char *const *g = font_glyph(*s);
        if (!g) continue;
        for (int row = 0; row < FONT_H; row++)
            for (int k = 0; k < FONT_W; k++)
                if (g[row][k] == '#') put(&c, x + k, row, col);
    }
    return c;
}
